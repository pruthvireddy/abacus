#!/usr/bin/env python3
"""Build the reproducible News EMA Move historical schedule archive.

Only category, timestamp, currency, title and importance select rows. Price or
move statistics never select a release. Native Pine stores compact counts;
archive JSON preserves the distinct titles and original source IDs.
"""
from __future__ import annotations
from collections import Counter, defaultdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CLASSIFIED = HERE.parent / '6e_news_study' / 'calendar_classification.json'
RAW = CLASSIFIED.with_name('calendar_raw.json')
INDICATOR = HERE.parent / 'news_ema_move.pine'
ARCHIVE_JSON = HERE / 'news_ema_calendar_archive.json'
FRAGMENT = HERE / 'news_ema_calendar_archive.pine'
MANIFEST = HERE / 'archive_manifest.json'
CATEGORIES = (
    ('us_employment_report', 'U.S. NFP / unemployment / earnings', 'selectNFP'),
    ('us_cpi', 'U.S. CPI / core CPI', 'selectCPI'),
    ('us_fomc_decision', 'FOMC decision / projections', 'selectFOMC'),
    ('us_fomc_press_conference', 'FOMC press conference', 'selectFedConference'),
    ('us_sp_pmi_flash', 'U.S. flash PMI', 'selectFlashPMI'),
    ('us_ism_manufacturing', 'U.S. ISM manufacturing', 'selectISM'),
    ('eu_ecb_decision', 'ECB rate decision', 'selectECB'),
    ('eu_ecb_press_conference', 'ECB press conference', 'selectECBConference'),
)
START = '2024-10-17T00:00:00Z'
END = '2026-10-17T00:00:00Z'
BEGIN_MARK = '// BEGIN GENERATED HISTORICAL CALENDAR ARCHIVE'
END_MARK = '// END GENERATED HISTORICAL CALENDAR ARCHIVE'

def ms(value):
    return int(datetime.fromisoformat(value.replace('Z', '+00:00')).timestamp() * 1000)

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def main():
    source = json.loads(CLASSIFIED.read_text())
    category_codes = {name: code for code, (name, _, _) in enumerate(CATEGORIES)}
    by_component = {}
    excluded = []
    for event in source['events']:
        category = event['category']
        if category not in category_codes or not ms(START) <= ms(event['date']) < ms(END):
            continue
        if event.get('excluded_from_analysis'):
            excluded.append(event)
            continue
        if event['importance'] not in (0, 1):
            raise AssertionError('Unknown importance scale')
        key = (ms(event['date']), event['currency'], event['title'])
        if key not in by_component:
            by_component[key] = dict(timestamp_ms=key[0], date=event['date'],
                category=category, category_code=category_codes[category],
                currency=key[1], title=key[2], importance=event['importance'],
                original_rows=[])
        component = by_component[key]
        assert (component['category'], component['importance']) == (category, event['importance'])
        component['original_rows'].append(dict(id=event['id'], period=event.get('period'),
            referenceDate=event.get('referenceDate')))
    components = sorted(by_component.values(), key=lambda row:
                        (row['timestamp_ms'], row['category_code'], row['importance'], row['title']))
    groups = defaultdict(list)
    for row in components:
        groups[(row['timestamp_ms'], row['category_code'], row['importance'])].append(row)
    records = [dict(timestamp_ms=t, category_code=c, importance=i, components=len(rows))
               for (t, c, i), rows in sorted(groups.items())]
    times = sorted({row['timestamp_ms'] for row in records})
    assert len(times) <= 160
    assert all(t % 900000 == 0 for t in times), 'Archive engine assumes audited 15m-grid releases'
    packed = ';'.join(f"{r['timestamp_ms']}:{r['category_code']}:{r['importance']}:{r['components']}" for r in records)
    archive = dict(schema_version=1, source=source['calendar_source'],
        coverage_start_inclusive=START, coverage_end_exclusive=END,
        category_map=[dict(code=i, category=c, label=label, pine_toggle=toggle)
                      for i, (c, label, toggle) in enumerate(CATEGORIES)],
        importance_map={'0': 'Medium', '1': 'High'},
        deduplication_key=['timestamp_ms', 'currency', 'title'],
        schedule_caveat='Audited corrected historical schedule, not a point-in-time record of what was announced before each release.',
        components=components, compact_records=records, excluded_rows=excluded)
    ARCHIVE_JSON.write_text(json.dumps(archive, indent=2) + '\n')
    labels = '\n'.join(f'        {code} => {json.dumps(label)}' for code, (_, label, _) in enumerate(CATEGORIES))
    enabled = '\n'.join(f'        {code} => {toggle}' for code, (_, _, toggle) in enumerate(CATEGORIES))
    fragment = f'''{BEGIN_MARK}
// Generated by news_ema_move_checks/build_archive.py from the audited TradingView
// calendar. Coverage is [2024-10-17, 2026-10-17) UTC. Historical dates may include
// subsequent schedule corrections: this is not an as-announced calendar replay.
// Source SHA256: {digest(CLASSIFIED)}
int ARCHIVE_START = {ms(START)}
int ARCHIVE_END = {ms(END)}

archiveCategoryName(int category) =>
    switch category
{labels}
        => "Unclassified"

archiveCategoryEnabled(int category) =>
    bool enabled = switch category
{enabled}
        => false
    enabled and (category <= 5 ? selectUSD : selectEUR)

buildArchive() =>
    array<NewsRelease> groups = array.new<NewsRelease>()
    string packed = "{packed}"
    array<string> rows = str.split(packed, ";")
    for rowIndex = 0 to rows.size() - 1
        array<string> fields = str.split(rows.get(rowIndex), ":")
        int scheduled = int(str.tonumber(fields.get(0)))
        int category = int(str.tonumber(fields.get(1)))
        int importance = int(str.tonumber(fields.get(2)))
        int components = int(str.tonumber(fields.get(3)))
        bool impactSelected = importance == 1 ? selectHigh : selectMedium
        if archiveCategoryEnabled(category) and impactSelected
            string detail = (category <= 5 ? "USD" : "EUR") + " · " + archiveCategoryName(category)
            detail += " (" + str.tostring(components) + (importance == 1 ? " high" : " medium") + "-impact title components)"
            if groups.size() > 0 and groups.last().scheduled == scheduled
                NewsRelease existing = groups.last()
                existing.releases += components
                existing.details += "\\n" + detail
            else
                groups.push(NewsRelease.new(scheduled, components, detail))
    groups

var array<NewsRelease> archiveGroups = buildArchive()
var array<int> archiveTimes = array.new_int()
if barstate.isfirst and archiveGroups.size() > 0
    for archiveIndex = 0 to archiveGroups.size() - 1
        archiveTimes.push(archiveGroups.get(archiveIndex).scheduled)
{END_MARK}
'''
    FRAGMENT.write_text(fragment)
    pine = INDICATOR.read_text()
    if BEGIN_MARK not in pine:
        raise RuntimeError('Install archive insertion markers before running builder')
    before, remainder = pine.split(BEGIN_MARK, 1)
    _, after = remainder.split(END_MARK, 1)
    pine = before + fragment.rstrip() + after
    INDICATOR.write_text(pine)
    counts = Counter(row['category'] for row in components)
    manifest = dict(schema_version=1, coverage_start_inclusive=START,
        coverage_end_exclusive=END, classified_input=str(CLASSIFIED),
        classified_sha256=digest(CLASSIFIED), raw_calendar_sha256=digest(RAW),
        classified_raw_source_sha256=source['source_sha256'],
        source_rows=sum(len(c['original_rows']) for c in components),
        distinct_title_components=len(components), compact_records=len(records),
        distinct_timestamps=len(times), default_us_timestamps=len({r['timestamp_ms'] for r in records if r['category_code']<=5}),
        off_grid_timestamps=0, excluded_rows=len(excluded),
        component_counts_by_category=dict(sorted(counts.items())),
        archive_json_sha256=digest(ARCHIVE_JSON), pine_fragment_sha256=digest(FRAGMENT),
        indicator_sha256=digest(INDICATOR), builder_sha256=digest(Path(__file__)),
        selection='All eight listed categories, excluded_from_analysis rows removed. No price/return selection; both medium(0) and high(1) archived; runtime toggles filter before exact-time grouping.')
    MANIFEST.write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps({key: manifest[key] for key in ('source_rows', 'distinct_title_components', 'compact_records', 'distinct_timestamps', 'default_us_timestamps', 'off_grid_timestamps')}, indent=2))

if __name__ == '__main__':
    main()
